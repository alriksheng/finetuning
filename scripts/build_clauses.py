cache = {}
def src(doc):
    if doc not in cache:
        cache[doc] = joined(find_file(DOCS[doc]['key']))
    return cache[doc]

def norm_marker(m):  # markers are typed with normal spacing; source join removes line breaks only
    return m

res, bad = [], []
for cid, doc, loc, a, b, nth in C:
    s = src(doc)
    # tolerate spaces after numbering like '3. ' vs '3.'
    def idx(txt, m, start=0):
        i = txt.find(m, start)
        if i >= 0: return i
        m2 = re.sub(r'\s+', '', m)
        # fallback on whitespace-free search
        stripped = re.sub(r'\s+', '', txt)
        return None
    i = s.find(a)
    if i < 0:
        # whitespace-insensitive fallback
        s2 = re.sub(r'\s+', '', s); a2 = re.sub(r'\s+', '', a); b2 = re.sub(r'\s+', '', b)
        i2 = s2.find(a2)
        if i2 < 0:
            bad.append((cid, 'start not found', a)); continue
        j2 = s2.find(b2, i2)
        if j2 < 0:
            bad.append((cid, 'end not found', b)); continue
        text = s2[i2:j2 + len(b2)]
    else:
        j = s.find(b, i)
        if j < 0:
            bad.append((cid, 'end not found', b)); continue
        text = s[i:j + len(b)]
    d = DOCS[doc]
    res.append(dict(clause_id=cid, doc_no=d['doc_no'], title=d['title'], location=loc,
                    text=text, effective_from=d['eff'], replaced_by=None))

for b in bad: print('BAD', b)
json.dump(res, open(OUT, 'w'), ensure_ascii=False, indent=1)
print(len(res), 'clauses ->', OUT)
for r in res: print(f"{r['clause_id']:14s} {len(r['text']):4d}  {r['text'][:60]}…{r['text'][-20:]}")
