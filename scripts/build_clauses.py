"""Build the clause pack (data/clauses/clauses.json) from the policy md files.
Clause text is sliced from the source by start/end markers, so quotes are verbatim by construction.
Run: python3 -I build_clauses.py <policy_dir> <out_json>"""
import sys, re, json, os, glob

POL_DIR, OUT = sys.argv[1], sys.argv[2]

def find_file(key):
    for f in glob.glob(os.path.join(POL_DIR, '*.md')):
        if key in os.path.basename(f):
            return f
    raise SystemExit(f'policy file not found: {key}')

def joined(path):
    out = []
    for ln in open(path, encoding='utf-8').read().splitlines():
        s = ln.strip()
        if re.fullmatch(r'-\s*\d+\s*-', s) or not s:
            continue
        out.append(s.lstrip('#').strip() if s.startswith('#') else s)
    return ''.join(out)

